package com.example.biliv3.design.tokens

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import androidx.compose.runtime.Composable
import com.example.biliv3.design.v3.BiliV3

/**
 * 明度带 —— 替代卡片的分组手段。
 *
 * ## 为什么是"带"而不是"卡片"
 *
 * 卡片是**盒子**：四边都断开、有圆角、有内边距 → 容器套容器 → 臃肿。
 * 明度带是**色块**：只有上下两条边界、左右贴到屏幕边 → 不产生"盒子感"。
 *
 * 这是本次重构的核心：**分组靠背景色的边界，不靠容器的边界。**
 *
 * ## 三档足够
 *
 * 深色下投影不可见 → 分层只能靠明度差。
 * 档位再多会变成"斑马纹"，三档是上限。
 *
 * ---
 *
 * ## 🔴 v1.6.9：改为**主题感知**
 *
 * 原来是硬编码的深色（`#0E1116` / `#141922` / `#0A0D12`）——
 * 浅色主题下这三档全都会变成**黑块**。
 *
 * 现在按主题返回：
 * - 深色：原来的深蓝黑三档（靠"提亮"分层）
 * - 浅色：白 / 浅灰 / 更浅灰（靠"压暗"分层，方向相反）
 *
 * ⚠️ 语义**不变**：`flat` 恒等于"页面底"、`raised` 恒为"抬升一档"、
 * `sunken` 恒为"下沉一档" —— 变的只是"抬升"在浅色下意味着**更暗**。
 */
object Band {
    /** 最底一档。与页面底同值 —— 内容直接排在上面。 */
    val flat: Color
        @Composable get() = if (BiliV3.colors.isLight) {
            // 浅色：页面底就是纯白
            Color(0xFFFFFFFF)
        } else {
            Color(0xFF0E1116)
        }

    /** 抬升一档。用于需要与主区分开的区块。 */
    val raised: Color
        @Composable get() = if (BiliV3.colors.isLight) {
            // ⚠️ 浅色下"抬升"= **更暗**（靠压暗拉开距离），不是更亮
            Color(0xFFF2F2F7)
        } else {
            Color(0xFF141922)
        }

    /** 下沉一档。用于"凹进去"的区域（如播放器周边、输入区）。 */
    val sunken: Color
        @Composable get() = if (BiliV3.colors.isLight) {
            Color(0xFFE5E5EA)
        } else {
            Color(0xFF0A0D12)
        }
}

/**
 * 发丝线 —— 唯一允许的硬边界。
 *
 * ## 使用约束（重要）
 *
 * **只在必须断开的地方出现。**
 *
 * 如果每两个元素之间都画线，界面会变成表格 —— 那是另一种臃肿。
 * 正确的用法是：明度带已经分组了，线只用在**带内部还需要细分**的地方。
 *
 * 优先用 [Rhythm] 的间距差分组，线是**兜底手段**。
 *
 * ---
 *
 * ## 🔴 v1.6.9：改为**主题感知**（原先是硬编码白色）
 *
 * 原来这里是 `Color(0x1AFFFFFF)` / `Color(0x0DFFFFFF)` ——
 * **白色 10% / 5%，与主题无关**。
 *
 * 在深色下没问题（白线压在暗底上可见）。但浅色主题下，
 * **白线画在白底上 = 完全不可见** —— 实测顶栏下方那条分隔线
 * 在截图里是纯 `(255,255,255)`，对比度 **1.00:1**。
 *
 * 影响面：`Rule.color` / `Rule.subtle` 被 **62 处、34 个文件**引用，
 * 全项目的分组边界一次性失效。
 *
 * ### 怎么改的
 *
 * 改成 `@Composable` getter，**按主题明暗返回对应颜色**：
 * 深色 → 白线（提亮边界）；浅色 → 黑线（压出边界）。
 *
 * ⚠️ **调用方无需改动**：两种调用形态（默认参数 `= Rule.color`、
 * 显式传参 `color = Rule.subtle`）都已在 `@Composable` 作用域内，
 * 所以加 `@Composable` 不会破坏任何调用点 —— 这是选这个方案的原因。
 *
 * ⚠️ **不要在非 `@Composable` 上下文引用这两个值**（编译期会报错，
 * 不会静默失效）。
 */
object Rule {
    /**
     * 主发丝线。
     *
     * - 深色：白 10%（`#1AFFFFFF`）—— 比旧 `borderHairline` 略亮，
     *   它承担唯一的分组职责
     * - 浅色：**黑 12%**（`#1F000000`）—— 方向必须反过来，
     *   浅色下靠"压暗"表达边界
     *
     * ⚠️ 浅色取 0.12 而不是深色对应的 0.10：白底上的淡灰线
     * 比暗底上的淡白线更难察觉（人眼对暗色的分辨力低于亮色），
     * 实测 0.10 在白色上几乎看不见。
     */
    val color: Color
        @Composable get() = if (BiliV3.colors.isLight) {
            Color(0x1F000000)
        } else {
            Color(0x1AFFFFFF)
        }

    /**
     * 更弱的一档，用于带内部细分。
     *
     * - 深色：白 5%
     * - 浅色：黑 8%
     */
    val subtle: Color
        @Composable get() = if (BiliV3.colors.isLight) {
            Color(0x14000000)
        } else {
            Color(0x0DFFFFFF)
        }

    val width = 1.dp
}

/**
 * 纵向节奏 —— 零线条分组的前提。
 *
 * ## 唯一规则：组间距 ≥ 2 × 组内间距
 *
 * 没有节奏差，留白就只是空白 —— 用户看不出"这里是一组"。
 * 这是"不用卡片也能分组"能成立的**唯一依据**。
 *
 * ## 🔴 配套规则：间距**只由下方区块提供**（全站统一）
 *
 * 这条规则是踩过坑才立的：
 *
 * 详情页的 UP 信息块给了 `top = between` + `bottom = between`，
 * 而下一个区块（分P）上边**也**给了 `between`
 * → 两块之间实际是 **28 + 28 = 56dp**，视觉上是一条突兀的空白带
 * （实测截图里互动栏与分P之间就是这个问题）。
 *
 * **规则：任何区块只在自己的 `top` 上加组间距，`bottom` 一律不加。**
 * 这样任意两块之间恒为一份间距，不会因为"两边都加"而翻倍。
 */
object Rhythm {
    /** 组内元素间距（标题与副标题、元信息行）。 */
    val inGroup = 8.dp

    /** 组与组之间。刻意是 [inGroup] 的 3.5 倍 —— 差得够明显才读得出分组。 */
    val between = 28.dp

    /** 章节之间（比 [between] 再大一档）。 */
    val section = 44.dp
}

/**
 * 压印 —— 深色下**唯一**能做出"内凹"的手段。
 *
 * ## 为什么投影做不出内凹
 *
 * 投影需要"亮底 + 暗影"才有立体感。深色底上投影渲染出来几乎为零
 * （这是项目里早就记录过的事实）。
 *
 * 内凹的物理表现是**上边暗、下边亮**（光从上方来，上沿背光）。
 * 两条 1dp 线就能表达，零性能开销。
 */
object Emboss {
    /** 上边暗线。 */
    val top = Color(0x14000000)

    /** 下边亮线。 */
    val bottom = Color(0x0FFFFFFF)
}

/**
 * 颗粒 —— 去掉"数字纯色"的塑料感。
 *
 * ## 为什么需要它
 *
 * 平面极简最大的问题是"素到没性格"。纯色大面积铺开会有明显的
 * **数字感**（像没有印上纸的电子墨水）。
 *
 * 颗粒用极低成本解决：一层 2~4% 的噪点贴图，不新增任何 UI 元素，
 * 却让表面从"色块"变成"材质"。
 *
 * ## 性能
 *
 * 噪点图**只生成一次**（进程级缓存），绘制是一次 `drawRect` + shader 平铺。
 * 开销远低于模糊，但仍归入 [com.example.biliv3.design.DeviceTier] 的降级范围：
 * 低端档直接不画。
 */
object Grain {
    /** 透明度。超过 5% 会显脏；低于 2% 看不出。 */
    const val ALPHA = 0.032f

    /** 噪点图边长。128 足够（平铺后看不出重复）。 */
    const val TILE = 128
}
